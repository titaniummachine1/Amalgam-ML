"""Export value-head MLP checkpoint -> C++ header (int8 + fp32 scales).
Same scheme as export_int8.py. MLP: 101->32 (ReLU) ->5 (logits, sigmoid in C++).
Usage: python ml/export_value.py value_simB.pt <dst.h>
Verifies by dequant reload + forward match."""
import os
import sys

import numpy as np
import torch
import torch.nn as nn

D = os.path.join(os.path.expanduser('~'), 'Downloads', 'mge_ds')


class Val(nn.Module):
    def __init__(self):
        super().__init__()
        self.mlp = nn.Sequential(nn.Linear(96 + 5, 32), nn.ReLU(), nn.Linear(32, 5))

    def forward(self, x):
        return self.mlp(x)


def qparam(p):
    s = p.abs().max().item() / 127.0
    q = torch.round(p / s).clamp(-128, 127).to(torch.int8)
    return q.numpy(), np.float32(s)


def main():
    src, dst = sys.argv[1], sys.argv[2]
    sd = torch.load(os.path.join(D, src) if not os.path.isabs(src) else src,
                    map_location='cpu')
    names = ['mlp.0.weight', 'mlp.0.bias', 'mlp.2.weight', 'mlp.2.bias']
    blobs = {}
    for n in names:
        q, s = qparam(sd[n].float())
        blobs[n] = (q, s)
    ref = Val()
    ref.load_state_dict(sd)
    tst = Val()
    dsd = {}
    for n in names:
        q, s = blobs[n]
        dsd[n] = torch.from_numpy(q.astype(np.float32)) * s
    tst.load_state_dict(dsd)
    ref.eval()
    tst.eval()
    with torch.no_grad():
        x = torch.randn(2, 101)
        err = (ref(x) - tst(x)).abs().max().item()
    print('max forward err after int8 roundtrip: %.6f' % err, flush=True)
    L = []
    L.append('// auto-generated by ml/export_value.py from %s (do not edit)' % src)
    L.append('#pragma once')
    L.append('#include <cstdint>')
    L.append('namespace BehaviorValue {')
    for n in names:
        q, s = blobs[n]
        var = n.replace('.', '_')
        L.append('constexpr float kScale_%s = %rf;' % (var, float(s)))
        flat = q.flatten()
        L.append('const int8_t kW_%s[%d] = {%s};' % (var, flat.size,
                                                     ','.join(str(int(v)) for v in flat)))
    L.append('} // namespace BehaviorValue')
    with open(dst, 'w') as f:
        f.write('\n'.join(L) + '\n')
    print('wrote', dst, flush=True)


if __name__ == '__main__':
    main()
