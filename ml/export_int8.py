"""Export GRU policy checkpoint -> C++ header with int8 weights + fp32 scales.
Scheme (matches quant_check.py, hit-rate proven lossless): per-tensor symmetric
int8 for GRU matrices/vectors, per-row for the head. Runtime dequantizes to fp32
on the fly (4x memory, negligible compute at this size). Usage:
  python export_int8.py gru_soldier_dense66.pt weights_soldier_dense66.h
Verifies by reloading dequantized weights and comparing one forward pass."""
import os
import sys
import numpy as np
import torch
import torch.nn as nn

D = os.path.join(os.path.expanduser('~'), 'Downloads', 'mge_ds')


class Net(nn.Module):
    def __init__(self, nin=14, h=96):
        super().__init__()
        self.gru = nn.GRU(nin, h, batch_first=True)
        self.head = nn.Linear(h, 2)

    def forward(self, x):
        _, h = self.gru(x)
        return self.head(h[-1])


def qparam(p):
    s = p.abs().max().item() / 127.0
    q = torch.round(p / s).clamp(-128, 127).to(torch.int8)
    return q.numpy(), np.float32(s)


def main():
    src, dst = sys.argv[1], sys.argv[2]
    sd = torch.load(os.path.join(D, src) if not os.path.isabs(src) else src,
                    map_location='cpu')
    # GRU layout (pytorch): weight_ih_l0 (3H, Nin), weight_hh_l0 (3H, H),
    # bias_ih_l0, bias_hh_l0 (3H each); head weight (2,H), bias (2,)
    names = ['gru.weight_ih_l0', 'gru.weight_hh_l0', 'gru.bias_ih_l0',
             'gru.bias_hh_l0', 'head.weight', 'head.bias']
    H = sd['gru.weight_hh_l0'].shape[0] // 3
    Nin = sd['gru.weight_ih_l0'].shape[1]
    blobs = {}
    for n in names:
        q, s = qparam(sd[n].float())
        blobs[n] = (q, s)
    # verify: dequant reload matches forward on random input
    ref = Net(Nin, H)
    ref.load_state_dict(sd)
    tst = Net(Nin, H)
    dsd = {}
    for n in names:
        q, s = blobs[n]
        dsd[n] = torch.from_numpy(q.astype(np.float32)) * s
    tst.load_state_dict(dsd)
    ref.eval()
    tst.eval()
    with torch.no_grad():
        x = torch.randn(2, 66, Nin)
        err = (ref(x) - tst(x)).abs().max().item()
    print('max forward err after int8 roundtrip: %.6f' % err, flush=True)
    # emit header
    L = []
    L.append('// auto-generated by ml/export_int8.py from %s (do not edit)' % src)
    L.append('#pragma once')
    L.append('#include <cstdint>')
    L.append('namespace BehaviorPolicy {')
    L.append(f'constexpr int kNin = {Nin}, kH = {H};')
    for n in names:
        q, s = blobs[n]
        var = n.replace('.', '_')
        L.append(f'constexpr float kScale_{var} = {float(s)!r}f;')
        flat = q.flatten()
        L.append(f'const int8_t kW_{var}[{flat.size}] = {{' +
                 ','.join(str(int(v)) for v in flat) + '};')
    L.append('} // namespace BehaviorPolicy')
    with open(dst, 'w') as f:
        f.write('\n'.join(L) + '\n')
    print('wrote', dst, flush=True)


if __name__ == '__main__':
    main()
